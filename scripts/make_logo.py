"""Trace public/logo.png into three SVG paths (topChevron, diamond, bottomChevron).

Pipeline: threshold -> connected components (3 pieces) -> marching-squares contour on an
upsampled mask -> Douglas-Peucker simplification -> map into a 100x100 viewBox.
Writes src/logoPaths.ts and public/logo-white.png (inverted, transparent).
"""
import json, os
import numpy as np
from PIL import Image
from scipy import ndimage
from skimage import measure

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "public", "logo.png")

im = Image.open(SRC).convert("RGBA")
a = np.array(im).astype(float)
lum = a[..., :3].mean(axis=2)
alpha = a[..., 3]
mask = (lum < 128) & (alpha > 128)

# --- connected components, sorted top -> bottom
lab, n = ndimage.label(mask, structure=np.ones((3, 3)))
boxes = ndimage.find_objects(lab)
comps = []
for i, sl in enumerate(boxes, start=1):
    m = lab[sl] == i
    cy, cx = ndimage.center_of_mass(m)
    comps.append({"id": i, "y0": sl[0].start, "y1": sl[0].stop, "x0": sl[1].start,
                  "x1": sl[1].stop, "cy": cy + sl[0].start, "cx": cx + sl[1].start,
                  "size": int(m.sum())})
comps = [c for c in comps if c["size"] > 40]
assert len(comps) == 3, f"expected 3 logo pieces, got {len(comps)}"
comps.sort(key=lambda c: c["cy"])
# middle piece (by centre y) is the diamond; the outer two are the chevrons
names = ["topChevron", "diamond", "bottomChevron"]
# diamond is the piece whose centre is closest to the logo centre
cy_all = (min(c["y0"] for c in comps) + max(c["y1"] for c in comps)) / 2
cx_all = (min(c["x0"] for c in comps) + max(c["x1"] for c in comps)) / 2
diamond = min(comps, key=lambda c: (c["cy"] - cy_all) ** 2 + (c["cx"] - cx_all) ** 2)
chevs = sorted([c for c in comps if c is not diamond], key=lambda c: c["cy"])
ordered = {"topChevron": chevs[0], "diamond": diamond, "bottomChevron": chevs[1]}

# logo-wide frame (union bbox) => normalise into 100x100 with a small margin
X0 = min(c["x0"] for c in comps); X1 = max(c["x1"] for c in comps)
Y0 = min(c["y0"] for c in comps); Y1 = max(c["y1"] for c in comps)
span = max(X1 - X0, Y1 - Y0)
pad = 4.0
scale = (100 - 2 * pad) / span
ox = (100 - (X1 - X0) * scale) / 2 - X0 * scale
oy = (100 - (Y1 - Y0) * scale) / 2 - Y0 * scale


def dp(points, eps):
    """Douglas-Peucker on an (N,2) array of points, closed-ring safe."""
    if len(points) < 3:
        return points
    start, end = points[0], points[-1]
    seg = end - start
    norm = np.hypot(*seg)
    if norm == 0:
        d = np.hypot(*(points - start).T)
    else:
        d = np.abs(seg[0] * (points[:, 1] - start[1]) - seg[1] * (points[:, 0] - start[0])) / norm
    idx = int(np.argmax(d))
    if d[idx] > eps:
        left = dp(points[: idx + 1], eps)
        right = dp(points[idx:], eps)
        return np.vstack([left[:-1], right])
    return np.vstack([start, end])


def contour_path(c):
    m = (lab[c["y0"]:c["y1"], c["x0"]:c["x1"]] == c["id"]).astype(float)
    m = np.pad(m, 3)                       # keep contours closed at crop edges
    up = 8
    big = np.kron(m, np.ones((up, up)))
    big = ndimage.gaussian_filter(big, 3)
    filled = ndimage.binary_fill_holes(big > 0.5).astype(float)
    cs = measure.find_contours(filled, 0.5)

    def area(r):
        y, x = r[:, 0], r[:, 1]
        return 0.5 * abs(np.dot(x, np.roll(y, 1)) - np.dot(y, np.roll(x, 1)))

    ring = max(cs, key=area)               # outer boundary = largest enclosed area
    # back to source-pixel coordinates (undo upsample, padding, crop offset)
    ys = (ring[:, 0] / up) - 3 + c["y0"] + 0.5 - 0.5 / up
    xs = (ring[:, 1] / up) - 3 + c["x0"] + 0.5 - 0.5 / up
    pts = np.stack([xs, ys], axis=1)
    closed = np.vstack([pts, pts[:1]])
    simp = measure.approximate_polygon(closed, tolerance=0.25)
    if np.allclose(simp[0], simp[-1]):
        simp = simp[:-1]
    out = []
    for x, y in simp:
        out.append((round(x * scale + ox, 2), round(y * scale + oy, 2)))
    return out, len(ring)


result = {}
for name in names:
    pts, raw = contour_path(ordered[name])
    d = "M" + " L".join(f"{x:g} {y:g}" for x, y in pts) + " Z"
    result[name] = {"d": d, "points": len(pts), "rawContour": raw,
                    "bbox100": [round(ordered[name]["x0"]*scale+ox,2), round(ordered[name]["y0"]*scale+oy,2),
                                round(ordered[name]["x1"]*scale+ox,2), round(ordered[name]["y1"]*scale+oy,2)]}

with open(os.path.join(ROOT, "src", "logoPaths.ts"), "w") as f:
    f.write("// Generated by scripts/make_logo.py from public/logo.png — do not hand-edit.\n")
    f.write("// viewBox 0 0 100 100. Three pieces: top chevron, diamond, bottom chevron.\n")
    f.write("export const LOGO_PATHS = {\n")
    for name in names:
        f.write(f"  {name}: {json.dumps(result[name]['d'])},\n")
    f.write("} as const;\n")
    f.write(f"export const LOGO_TRANSFORM = {{ scale: {scale:.6f}, ox: {ox:.4f}, oy: {oy:.4f} }} as const;\n")

# inverted white logo with transparent background
rgb = np.zeros((100, 150, 4), dtype=np.uint8)
rgb[..., 0:3] = 245
rgb[..., 3] = (mask.astype(np.uint8) * 255)
Image.fromarray(rgb, "RGBA").save(os.path.join(ROOT, "public", "logo-white.png"))

print(json.dumps({k: {"points": v["points"], "bbox100": v["bbox100"]} for k, v in result.items()}, indent=1))
print("scale", scale, "ox", ox, "oy", oy)

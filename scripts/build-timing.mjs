// Reads the real VO clip durations (ffprobe) and writes src/timing.ts:
// scene starts/durations on an 18-frame beat grid (100 BPM @ 30 fps),
// the VO start inside each scene, and estimated hero-word frames.
// Hero-word frames are proportional to character position in the VO line; verify with
// extracted frames after the proof render (R7). Edit VO_LINES/HEROES, then rerun.
import { execFileSync } from "node:child_process";
import { writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const FPS = 30;
const BEAT = 18;            // 100 BPM in frames: 60/100 s * 30 fps
const LEAD = 9;             // visuals start 0.3 s before VO (scene 1 starts on frame 0 — R1)
const TAIL = 30;            // 1.0 s resolved hold after VO (R4 needs >= 12 frames)
const VISUAL_VISUAL_LAG = 6; // R7: visual leads spoken word by ~6 frames

const FFPROBE = process.env.FFPROBE ?? join(ROOT, "node_modules/@remotion/compositor-linux-x64-gnu/ffprobe");
const probe = existsSync(FFPROBE) ? FFPROBE : "ffprobe";

const SCENES = [
  { id: 1, text: "Everyone's posting. Nobody's competing.", heroes: ["competing"] },
  { id: 2, text: "AustroClash. Where ideas go to fight.", heroes: ["fight"] },
  { id: 3, text: "Post in the Arena. Choose your category.", heroes: ["Arena"] },
  { id: 4, text: "Every month, the post with the most votes wins — and its author is crowned King.", heroes: ["King"] },
  { id: 5, text: "The Kingboard remembers every reign.", heroes: ["remembers"] },
  { id: 6, text: "Build your profile. Earn your badges. Form Squads with your Allies.", heroes: ["Squads"] },
  { id: 7, text: "Talk in private. Message anyone you're allowed to.", heroes: ["private"] },
  { id: 8, text: "Need something built? Post it in AUSTRO VAR — the Value and Resource Arena. Providers respond. You choose.", heroes: ["VAR", "choose"] },
  { id: 9, text: "Dress your identity in the Austro Store. Sign it with your AustroSignature. Spend AustroPoints. And let the AI Referee keep it fair.", heroes: ["Store", "AustroSignature", "AustroPoints", "Referee"] },
  { id: 10, text: "Stop scrolling. Start clashing. AustroClash.", heroes: ["scrolling", "clashing", "AustroClash"] },
];

const voDuration = (file) => {
  const out = execFileSync(probe, ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", file]).toString();
  return parseFloat(out.trim());
};

const heroFrameInText = (text, word, voFrames) => {
  const idx = text.indexOf(word);
  if (idx < 0) throw new Error(`hero "${word}" not found in "${text}"`);
  const center = (idx + word.length / 2) / text.length;
  return Math.round(center * voFrames);
};

let cursor = 0;
const out = [];
for (const s of SCENES) {
  const file = join(ROOT, "public/vo", `${String(s.id).padStart(2, "0")}.mp3`);
  const voFrames = Math.round(voDuration(file) * FPS);
  const lead = s.id === 1 ? 0 : LEAD;
  const tail = s.id === 10 ? TAIL + 75 : TAIL; // scene 10 holds 2.5 s on lockup (R13)
  const raw = lead + voFrames + tail;
  const duration = Math.ceil(raw / BEAT) * BEAT;   // snap to beat grid
  const heroes = s.heroes.map((w) => {
    const audioFrame = cursor + lead + heroFrameInText(s.text, w, voFrames);
    return { word: w, audioFrame, visualFrame: audioFrame - VISUAL_VISUAL_LAG };
  });
  out.push({ id: s.id, start: cursor, duration, voStart: cursor + lead, voFrames, text: s.text, heroes });
  cursor += duration;
}

const total = cursor;
const ts = `// AUTO-GENERATED by scripts/build-timing.mjs — do not hand-edit. Rerun: npm run build:timing
export const FPS = ${FPS};
export const BEAT_FRAMES = ${BEAT};
export const TOTAL_FRAMES = ${total};
export type Hero = { word: string; audioFrame: number; visualFrame: number };
export type SceneTiming = { id: number; start: number; duration: number; voStart: number; voFrames: number; text: string; heroes: Hero[] };
export const SCENES: SceneTiming[] = ${JSON.stringify(out, null, 2)};
export const SCENE = (id: number): SceneTiming => SCENES[id - 1];
`;
writeFileSync(join(ROOT, "src/timing.ts"), ts);
console.log(out.map((s) => `S${s.id}: start=${s.start} dur=${s.duration} (${(s.duration / FPS).toFixed(2)}s) vo=${s.voFrames}f heroes=${s.heroes.map((h) => `${h.word}@${h.audioFrame}`).join(",")}`).join("\n"));
console.log(`TOTAL ${total} frames = ${(total / FPS).toFixed(2)} s`);
